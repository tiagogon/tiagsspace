<?php
/**
 * Query filters for post visibility and cache management.
 *
 * Includes: hide posts from index/archives/feeds (ACF field), exclude hidden
 * posts from adjacent navigation, purge Table Index cache on post changes.
 *
 * @package tiagsspace
 */

/**
 * Hide posts from listings when a specific ACF field is checked.
 *
 * Behaviour:
 * - If the ACF true/false field is set (value '1'), the post remains public
 *   but will NOT appear on: homepage index, any feed, or any archive
 *   (including category/tag, custom taxonomy, author, date, and CPT archives).
 * - Single post pages remain accessible.
 *
 * Configuration:
 * - Uses an ACF true/false field with the meta key
 *   'hide_post_from_main_page_archives_and_feed'.
 *
 * Notes on ACF storage:
 * - ACF true/false stores '1' (string) when checked; when unchecked it may
 *   store '0' or no meta row at all. We therefore include posts where the meta
 *   does not exist OR where the value is not '1'.
 */
function tiagsspace_hide_posts_from_index_archives_feeds( $query ) {
    // Only affect the main front-end query; never change admin or secondary queries.
    if ( is_admin() || ! $query->is_main_query() ) {
        return;
    }

    // Decide where to apply:
    // - home (posts index)
    // - any feed
    // - any archive (tax, CPT, author, date, etc.)
    // - search results
    // - REST API collection queries
    $apply = (
        $query->is_home() ||
        $query->is_feed() ||
        $query->is_archive() ||
        $query->is_search() ||
        ( defined('REST_REQUEST') && REST_REQUEST )
    );
    if ( ! $apply ) {
        return;
    }

    // Meta key for the ACF true/false field. Expect '1' (string) when checked.
    $meta_key = 'hide_post_from_main_page_archives_and_feed';

    // Merge with any existing meta_query so we don't clobber other constraints.
    $existing_meta_query = $query->get( 'meta_query' );
    if ( ! is_array( $existing_meta_query ) ) {
        $existing_meta_query = array();
    }

    // Add an OR group that keeps posts NOT marked to hide:
    // 1) posts without the meta key at all; OR
    // 2) posts where the meta value is not '1'.
    // The effect is that posts with value '1' are excluded from these listings.
    $existing_meta_query[] = array(
        'relation' => 'OR',
        array(
            'key'     => $meta_key,
            'compare' => 'NOT EXISTS',
        ),
        array(
            'key'     => $meta_key,
            'value'   => '1',
            'compare' => '!=',
        ),
    );

    // Apply the augmented meta_query back onto the WP_Query instance.
    $query->set( 'meta_query', $existing_meta_query );
}
// Hook into the query build phase so we can alter parameters before SQL runs.
add_action( 'pre_get_posts', 'tiagsspace_hide_posts_from_index_archives_feeds' );


/**
 * Exclude posts flagged with the ACF field
 * 'hide_post_from_main_page_archives_and_feed' from previous/next
 * navigation on single post pages. If the immediately adjacent post is
 * hidden, WordPress will continue searching earlier/later until it
 * finds a visible one, effectively skipping hidden posts in the
 * sequence.
 *
 * We hook into the SQL fragments generated by get_adjacent_post() via
 * the 'get_previous_post_where' and 'get_next_post_where' filters.
 * Core aliases the posts table as `p` in these WHERE clauses, so we
 * can safely reference `p.ID`.
 */
function tiagsspace_exclude_hidden_adjacent_where( $where ) {
    global $wpdb;
    $meta_key = 'hide_post_from_main_page_archives_and_feed';
    // Exclude any post with the meta key value '1' (ACF true state).
    $where .= " AND p.ID NOT IN (SELECT post_id FROM {$wpdb->postmeta} WHERE meta_key='{$meta_key}' AND meta_value='1')";
    return $where;
}
add_filter( 'get_previous_post_where', 'tiagsspace_exclude_hidden_adjacent_where' );
add_filter( 'get_next_post_where', 'tiagsspace_exclude_hidden_adjacent_where' );


/************* PURGE TABLE INDEX CACHE ON POST CHANGES *************/
// When any post is published, unpublished, trashed or updated,
// ask W3 Total Cache to flush the cached Table Index page.
function tiagsspace_purge_table_index_cache( $new_status, $old_status, $post ) {
    // Act on status changes (publish, unpublish, trash) OR updates to published posts
    if ( $new_status !== 'publish' && $old_status !== 'publish' ) return;

    // Find the page using the "Table Index" template
    $pages = get_pages( array(
        'meta_key'   => '_wp_page_template',
        'meta_value' => 'page-table-index.php',
        'number'     => 1,
    ) );

    if ( empty( $pages ) ) return;

    $page_id = $pages[0]->ID;
    $url = get_permalink( $page_id );

    // W3 Total Cache: flush by URL
    if ( function_exists( 'w3tc_flush_url' ) ) {
        call_user_func( 'w3tc_flush_url', $url );
    // Fallback: flush entire page cache
    } elseif ( function_exists( 'w3tc_flush_posts' ) ) {
        call_user_func( 'w3tc_flush_posts' );
    }
}
add_action( 'transition_post_status', 'tiagsspace_purge_table_index_cache', 10, 3 );
